const quizForm = document.getElementById("quizForm") as HTMLFormElement;
const result = document.getElementById("result") as HTMLDivElement;

questions.forEach((item: Question, index: number) => {

    const questionDiv = document.createElement("div");

    questionDiv.classList.add("question");

    questionDiv.innerHTML = `
        <p>${item.q}</p>

        ${item.o.map((option: string) => `
            <label>
                <input 
                    type="radio" 
                    name="q${index}" 
                    value="${option}"
                >
                ${option}
            </label>
        `).join("")}
    `;

    quizForm.appendChild(questionDiv);

});

function gradeQuiz(): void {

    let score: number = 0;

    questions.forEach((item: Question, index: number) => {

        const selected = document.querySelector(
            `input[name="q${index}"]:checked`
        ) as HTMLInputElement | null;

        if(selected && selected.value === item.a){
            score++;
        }

    });

    const percentage: number = Math.round(
        (score / questions.length) * 100
    );

    result.innerHTML = `
        <h2>You scored ${score}/50</h2>
        <h1>${percentage}%</h1>
    `;

    window.scrollTo({
        top: document.body.scrollHeight,
        behavior: "smooth"
    });

}
